"""scripts/refresh_lock.py — lock closure/render/check driven with fake distributions.

Incident 2026-10-24: floating transitive packages (preshed 3.0.14) broke a fresh
install. Class: proposed BC (floating transitive dependencies).
"""
import importlib.util
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent.parent
_spec = importlib.util.spec_from_file_location("refresh_lock", ROOT / "scripts" / "refresh_lock.py")
rl = importlib.util.module_from_spec(_spec)
sys.modules["refresh_lock"] = rl
_spec.loader.exec_module(rl)

ENV = {"python_version": "3.11", "sys_platform": "linux", "platform_system": "Linux",
       "platform_machine": "x86_64", "python_full_version": "3.11.8", "os_name": "posix",
       "implementation_name": "cpython", "platform_python_implementation": "CPython",
       "implementation_version": "3.11.8", "platform_release": "", "platform_version": "",
       "extra": ""}

DISTS = {
    "app-dep": ("1.0", ["Sub_Pkg>=1", 'winonly; sys_platform == "win32"',
                        'opt-extra; extra == "fast"', "nvidia-cublas-cu12", "triton"]),
    "sub-pkg": ("2.5", ["leaf"]),
    "leaf": ("0.1", []),
    "winonly": ("9.9", []),
    "opt-extra": ("3.0", ["extra-leaf"]),
    "extra-leaf": ("4.0", []),
    "nvidia-cublas-cu12": ("12.0", []),
    "triton": ("3.0", []),
    "torch": ("2.11.0+cu126", ["nvidia-cublas-cu12", "setuptools<82"]),
    "setuptools": ("65.5.0", []),
    "en-core-web-sm": ("3.8.0", []),
    "pytest": ("9.0.0", []),
    "unrelated": ("1.0", []),
}


def reqs(*lines):
    return rl.parse_requirements(lines)


def test_closure_follows_markers_and_normalizes_names():
    pins = rl.closure(reqs("app-dep>=1"), DISTS, ENV)
    assert pins == {"app-dep": "1.0", "sub-pkg": "2.5", "leaf": "0.1"}  # no winonly, no extra


def test_closure_honours_extras_named_in_requirements():
    pins = rl.closure(reqs("app-dep[fast]"), DISTS, ENV)
    assert pins["opt-extra"] == "3.0" and pins["extra-leaf"] == "4.0"


def test_gpu_stack_and_model_package_excluded_local_label_stripped():
    pins = rl.closure(reqs("torch==2.11.0", "en_core_web_sm"), DISTS, ENV)
    assert pins == {"torch": "2.11.0"}


def test_installer_toolchain_is_never_pinned():
    """PR #104 CI: torch requires setuptools; a lock pin of the dev env's
    setuptools 65.5.0 made the torch CPU-index install unresolvable (that index
    carries no such version). pip/setuptools/wheel belong to the runner."""
    assert all(rl.is_excluded(n) for n in ("setuptools", "pip", "wheel"))
    pins = rl.closure(reqs("torch==2.11.0"), DISTS, ENV)
    assert "setuptools" not in pins


def test_unsatisfied_requirement_is_an_error_and_names_each():
    with pytest.raises(rl.LockError) as e:
        rl.build_lock("app-dep==9.9\nmissing-pkg>=1\n", DISTS, "3.11.8", "2026-10-24", ("pytest",))
    msg = str(e.value)
    assert "app-dep" in msg and "missing-pkg" in msg


def test_build_lock_header_and_sorted_pins():
    text = rl.build_lock("app-dep>=1\ntorch==2.11.0  # c\n", DISTS, "3.11.8", "2026-10-24", ("pytest",))
    assert text.startswith("# generated by scripts/refresh_lock.py")
    assert "do not edit by hand" in text and "-c requirements.lock.txt" in text
    assert "nvidia-" in text and "en_core_web_sm" in text  # exclusions explained
    assert rl.pin_lines(text) == sorted(rl.pin_lines(text))
    assert "torch==2.11.0" in rl.pin_lines(text) and "unrelated==1.0" not in rl.pin_lines(text)


def test_check_detects_stale_line_and_clean_lock(tmp_path):
    (tmp_path / "requirements.txt").write_text("app-dep>=1\n")
    fake = {"app-dep": ("1.0", []), "pytest": ("9.0.0", []), "pytest-asyncio": ("1", []),
            "pytest-cov": ("1", []), "fpdf2": ("1", []), "ruff": ("1", [])}
    assert rl.main([], root=tmp_path, read=lambda: fake) == 0
    assert rl.main(["--check"], root=tmp_path, read=lambda: fake) == 0
    lock = tmp_path / "requirements.lock.txt"
    lock.write_text(lock.read_text().replace("app-dep==1.0", "app-dep==0.9"))
    assert rl.main(["--check"], root=tmp_path, read=lambda: fake) == 1


def test_main_never_writes_when_requirement_unsatisfied(tmp_path):
    (tmp_path / "requirements.txt").write_text("app-dep==2.0\n")
    assert rl.main([], root=tmp_path, read=lambda: {"app-dep": ("1.0", [])}) == 1
    assert not (tmp_path / "requirements.lock.txt").exists()


# ---- environment consistency (referee round 2026-10-24) ----

def test_conflict_listed_in_pip_check_wording():
    d = {"chromadb": ("1.0.7", ["kubernetes"]),
         "kubernetes": ("34.1.0", ["urllib3<2.4.0,>=1.24.2"]),
         "urllib3": ("2.6.3", [])}
    assert rl.conflicts(reqs("chromadb"), d, ENV) == [
        "kubernetes 34.1.0 requires urllib3<2.4.0,>=1.24.2; env has 2.6.3"]


def test_build_lock_raises_on_kubernetes_urllib3_case(tmp_path):
    d = {"chromadb": ("1.0.7", ["kubernetes"]),
         "kubernetes": ("34.1.0", ["urllib3<2.4.0,>=1.24.2"]),
         "urllib3": ("2.6.3", []),
         "pytest": ("9", []), "pytest-asyncio": ("1", []), "pytest-cov": ("1", []),
         "fpdf2": ("1", []), "ruff": ("1", [])}
    with pytest.raises(rl.LockError) as e:
        rl.build_lock("chromadb==1.0.7\n", d, "3.11.8", "2026-10-24")
    msg = str(e.value)
    assert "kubernetes 34.1.0 requires urllib3<2.4.0,>=1.24.2; env has 2.6.3" in msg
    assert "the lock must be installable" in msg
    (tmp_path / "requirements.txt").write_text("chromadb==1.0.7\n")
    assert rl.main([], root=tmp_path, read=lambda: d) == 1
    assert not (tmp_path / "requirements.lock.txt").exists()


def test_marker_inactive_requirement_is_not_a_conflict():
    d = {"a": ("1.0", ['b<1; sys_platform == "win32"', 'c<1; extra == "x"']),
         "b": ("5.0", []), "c": ("5.0", [])}
    assert rl.conflicts(reqs("a"), d, ENV) == []


def test_dependency_outside_the_closure_is_ignored():
    d = {"a": ("1.0", []), "vastai": ("0.5.0", ["python-dateutil==2.6.1"]),
         "python-dateutil": ("2.9.0", [])}
    assert rl.conflicts(reqs("a"), d, ENV) == []
