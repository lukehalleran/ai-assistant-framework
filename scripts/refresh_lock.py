#!/usr/bin/env python
"""Generate requirements.lock.txt from the interpreter that runs this script.

Usage (run with the interpreter whose environment is the source of truth):
    <python> scripts/refresh_lock.py            # rewrite requirements.lock.txt
    <python> scripts/refresh_lock.py --check    # exit 1 if the lock is stale

Class: floating transitive dependencies (2026-10-24 preshed incident).
The lock is the dependency CLOSURE of requirements.txt + the CI tool packages,
resolved through importlib.metadata (markers evaluated, extras honoured, PEP 503
names). The core (closure/render/compare) is pure; only main() touches I/O.
"""
from __future__ import annotations

import argparse
import datetime as _dt
import importlib.metadata as _md
import re
import sys
from pathlib import Path
from typing import Callable, Dict, Iterable, List, Mapping, Optional, Sequence, Tuple

from packaging.markers import default_environment
from packaging.requirements import InvalidRequirement, Requirement

ROOT = Path(__file__).resolve().parent.parent

# Install lines of .github/workflows/tests.yml `test` job (pytest pytest-asyncio
# pytest-cov fpdf2 ruff); pyinstaller is included only when installed.
CI_TOOL_PACKAGES = ("pytest", "pytest-asyncio", "pytest-cov", "fpdf2", "ruff")
OPTIONAL_TOOL_PACKAGES = ("pyinstaller",)

EXCLUDED_PREFIXES = ("nvidia-", "cuda-")
EXCLUDED_NAMES = frozenset({"triton", "en-core-web-sm"})

HEADER_MARK = "# generated by scripts/refresh_lock.py"


class LockError(Exception):
    pass


def norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def strip_local(version: str) -> str:
    return version.split("+", 1)[0]


def is_excluded(name: str) -> bool:
    n = norm(name)
    return n in EXCLUDED_NAMES or n.startswith(EXCLUDED_PREFIXES)


def parse_requirements(lines: Iterable[str]) -> List[Requirement]:
    out = []
    for raw in lines:
        line = raw.split(" #", 1)[0].split("\t#", 1)[0]
        line = line.strip()
        if not line or line.startswith(("#", "-")):
            continue
        try:
            out.append(Requirement(line))
        except InvalidRequirement as e:
            raise LockError(f"unparseable requirement {raw.strip()!r}: {e}")
    return out


# dists: normalized name -> (version, [requires strings])
Dists = Mapping[str, Tuple[str, Sequence[str]]]


def unsatisfied(roots: Sequence[Requirement], dists: Dists) -> List[str]:
    bad = []
    for r in roots:
        d = dists.get(norm(r.name))
        if d is None:
            bad.append(f"{r.name}: not installed (requires {r.specifier or 'any'})")
        elif not r.specifier.contains(strip_local(d[0]), prereleases=True):
            bad.append(f"{r.name}: installed {d[0]}, requirements.txt wants {r.specifier}")
    return bad


def _walk(roots: Sequence[Requirement], dists: Dists,
          env: Optional[Dict[str, str]] = None):
    """(pins, edges): pins {name: version}; edges [(owner, owner_version, dep Requirement)]
    for every ACTIVE requirement (markers and extras evaluated) of every package reached."""
    base_env = dict(env or default_environment())
    seen: Dict[str, str] = {}
    edges: List[Tuple[str, str, Requirement]] = []
    stack: List[Tuple[str, Tuple[str, ...]]] = [
        (norm(r.name), tuple(sorted(r.extras))) for r in roots]
    done = set()
    while stack:
        name, extras = stack.pop()
        if is_excluded(name) or (name, extras) in done:
            continue
        done.add((name, extras))
        d = dists.get(name)
        if d is None:
            continue  # optional/absent: pip check, not the lock, reports it
        seen[name] = strip_local(d[0])
        for req_str in d[1]:
            try:
                dep = Requirement(req_str)
            except InvalidRequirement:
                continue
            if dep.marker is not None:
                active = False
                for extra in (extras or ("",)):
                    if dep.marker.evaluate({**base_env, "extra": extra}):
                        active = True
                        break
                if not active:
                    continue
            edges.append((name, seen[name], dep))
            stack.append((norm(dep.name), tuple(sorted(dep.extras))))
    return seen, edges


def closure(roots: Sequence[Requirement], dists: Dists,
            env: Optional[Dict[str, str]] = None) -> Dict[str, str]:
    """Pinned {name: version} for the roots and everything they pull in."""
    return _walk(roots, dists, env)[0]


def conflicts(roots: Sequence[Requirement], dists: Dists,
              env: Optional[Dict[str, str]] = None) -> List[str]:
    """Every active requirement inside the closure that the pinned version of its
    dependency violates (what `pip check` would report, scoped to the closure)."""
    pins, edges = _walk(roots, dists, env)
    out = set()
    for owner, owner_ver, dep in edges:
        have = pins.get(norm(dep.name))
        if have is None or is_excluded(dep.name):
            continue
        if not dep.specifier.contains(have, prereleases=True):
            out.add(f"{owner} {owner_ver} requires {dep.name}{dep.specifier}; env has {have}")
    return sorted(out)


def render(pins: Mapping[str, str], interpreter: str, today: str) -> str:
    header = [
        f"{HEADER_MARK} — do not edit by hand.",
        f"# interpreter: Python {interpreter}   date: {today}",
        "# install: pip install -r requirements.txt -c requirements.lock.txt",
        "# refresh: python scripts/refresh_lock.py   (verify: --check)",
        "# EXCLUDED on purpose: nvidia-*, triton, cuda-* (GPU stack: platform-specific;",
        "#   CI and the frozen CPU build install different torch variants) and",
        "#   en_core_web_sm (a URL package a constraints file cannot hold; `spacy download`",
        "#   picks the model matching the pinned spaCy). torch/torchvision are pinned",
        "#   WITHOUT their local label (2.11.0, not 2.11.0+cu126).",
    ]
    body = [f"{n}=={v}" for n, v in sorted(pins.items())]
    return "\n".join(header + body) + "\n"


def pin_lines(text: str) -> List[str]:
    return [l.strip() for l in text.splitlines() if l.strip() and not l.startswith("#")]


def diff_lines(current: str, expected: str) -> List[str]:
    cur, exp = set(pin_lines(current)), set(pin_lines(expected))
    return [f"- {l}" for l in sorted(cur - exp)] + [f"+ {l}" for l in sorted(exp - cur)]


def read_installed() -> Dict[str, Tuple[str, List[str]]]:
    out: Dict[str, Tuple[str, List[str]]] = {}
    for dist in _md.distributions():
        name = dist.metadata["Name"]
        if name:
            out[norm(name)] = (dist.version, list(dist.requires or []))
    return out


def build_lock(requirements_text: str, dists: Dists, interpreter: str,
               today: str, extra_tools: Sequence[str] = CI_TOOL_PACKAGES) -> str:
    roots = parse_requirements(requirements_text.splitlines())
    bad = unsatisfied(roots, dists)
    if bad:
        raise LockError("interpreter does not satisfy requirements.txt:\n  " + "\n  ".join(bad))
    tools = [Requirement(t) for t in extra_tools]
    tools += [Requirement(t) for t in OPTIONAL_TOOL_PACKAGES if norm(t) in dists]
    missing = [t.name for t in tools if norm(t.name) not in dists]
    if missing:
        raise LockError("CI tool packages not installed: " + ", ".join(missing))
    bad = conflicts(roots + tools, dists)
    if bad:
        raise LockError(
            "the environment is internally inconsistent:\n  " + "\n  ".join(bad)
            + "\nfix the environment (pip install ...) and re-run; the lock must be installable")
    return render(closure(roots + tools, dists), interpreter, today)


def main(argv: Optional[Sequence[str]] = None, root: Path = ROOT,
         read: Callable[[], Dists] = read_installed) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="compare, do not write")
    args = ap.parse_args(argv)
    interp = ".".join(map(str, sys.version_info[:3]))
    try:
        text = build_lock((root / "requirements.txt").read_text(encoding="utf-8"),
                          read(), interp, _dt.date.today().isoformat())
    except LockError as e:
        print(f"refresh_lock: {e}", file=sys.stderr)
        return 1
    lock = root / "requirements.lock.txt"
    if args.check:
        current = lock.read_text(encoding="utf-8") if lock.exists() else ""
        d = diff_lines(current, text)
        if d:
            print("requirements.lock.txt is out of date:\n" + "\n".join(d))
            return 1
        print("requirements.lock.txt is up to date")
        return 0
    lock.write_text(text, encoding="utf-8")
    print(f"wrote {lock} ({len(pin_lines(text))} pins)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
